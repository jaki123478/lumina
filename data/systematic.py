"""Systematic data for Lumina: Italian number words, arithmetic tables, definition frames.

Everything here is generated by rules from small tables, never copied from
another model. Some wording frames and some arithmetic pairs are held out for
validation, so validation measures generalization instead of memory.
"""
import random

UNITS = ["zero", "uno", "due", "tre", "quattro", "cinque", "sei", "sette", "otto", "nove", "dieci", "undici",
         "dodici", "tredici", "quattordici", "quindici", "sedici", "diciassette", "diciotto", "diciannove"]
TENS = ["venti", "trenta", "quaranta", "cinquanta", "sessanta", "settanta", "ottanta", "novanta"]


def words(n: int) -> str:
    if n < 20:
        return UNITS[n]
    if n == 100:
        return "cento"
    tens, unit = TENS[n // 10 - 2], n % 10
    if unit == 0:
        return tens
    if unit in (1, 8):
        return tens[:-1] + UNITS[unit]
    return tens + ("tré" if unit == 3 else UNITS[unit])


OPS = {
    "+": ("più", lambda a, b: a + b, ["+"]),
    "-": ("meno", lambda a, b: a - b, ["-"]),
    "*": ("per", lambda a, b: a * b, ["*", "x"]),
    "/": ("diviso", lambda a, b: a // b, ["/", ":"]),
}


def arithmetic_rows(rng: random.Random, held_out_share: float = 0.12):
    """Yield (question, answer, split) for all small exact operations on 0..10."""
    facts = []
    for a in range(11):
        for b in range(11):
            facts.append((a, "+", b))
            if a >= b:
                facts.append((a, "-", b))
            facts.append((a, "*", b))
            if b and a % b == 0:
                facts.append((a, "/", b))
    rng.shuffle(facts)
    held = set(facts[: int(len(facts) * held_out_share)])
    for a, op, b in facts:
        name, fn, symbols = OPS[op]
        result = fn(a, b)
        answer = f"{words(a).capitalize()} {name} {words(b)} fa {words(result)}."
        symbol = rng.choice(symbols)
        frames = [
            f"Quanto fa {a}{symbol}{b}?", f"Quanto fa {a} {symbol} {b}?", f"{a} {symbol} {b}", f"Calcola {a}{symbol}{b}",
            f"Quanto fa {words(a)} {name} {words(b)}?", f"{words(a)} {name} {words(b)}", f"Calcola {words(a)} {name} {words(b)}",
            f"Quanto fa {a} {name} {b}?",
        ]
        if (a, op, b) in held:
            yield rng.choice(frames), answer, "validation"
        else:
            for question in rng.sample(frames, 4):
                yield question, answer, "train"


# (first question of the topic in TOPICS, with article, "di"-form, "su"-form, plain name)
SUBJECTS = [
    ("Che cos'è un modello linguistico?", "un modello linguistico", "di un modello linguistico", "su un modello linguistico", "modello linguistico"),
    ("Cos'è un parametro?", "un parametro", "di un parametro", "su un parametro", "parametro"),
    ("Cos'è un token?", "un token", "di un token", "su un token", "token"),
    ("Cos'è un Transformer?", "un Transformer", "di un Transformer", "su un Transformer", "Transformer"),
    ("Cos'è una rete neurale?", "una rete neurale", "di una rete neurale", "su una rete neurale", "rete neurale"),
    ("Cos'è Python?", "Python", "di Python", "su Python", "Python"),
    ("Cos'è JavaScript?", "JavaScript", "di JavaScript", "su JavaScript", "JavaScript"),
    ("Cos'è HTML?", "HTML", "di HTML", "su HTML", "HTML"),
    ("Cos'è CSS?", "CSS", "di CSS", "su CSS", "CSS"),
    ("Cos'è un browser?", "un browser", "di un browser", "su un browser", "browser"),
    ("Cos'è una variabile?", "una variabile", "di una variabile", "su una variabile", "variabile"),
    ("Cos'è una funzione?", "una funzione", "di una funzione", "su una funzione", "funzione"),
    ("Cos'è il Sole?", "il Sole", "del Sole", "sul Sole", "Sole"),
    ("Cos'è la Luna?", "la Luna", "della Luna", "sulla Luna", "Luna"),
    ("Cos'è l'acqua?", "l'acqua", "dell'acqua", "sull'acqua", "acqua"),
    ("Cos'è un gatto?", "un gatto", "di un gatto", "su un gatto", "gatto"),
    ("Cos'è un cane?", "un cane", "di un cane", "su un cane", "cane"),
    ("Cos'è un libro?", "un libro", "di un libro", "su un libro", "libro"),
    ("Cos'è la temperatura?", "la temperatura", "della temperatura", "sulla temperatura", "temperatura"),
]
TRAIN_FRAMES = ["Cos'è {art}?", "Che cos'è {art}?", "Cosa è {art}?", "Spiegami {art}", "Spiega {art}", "Parlami {di}",
                "Dimmi qualcosa {su}", "Cosa significa {plain}?", "{plain}: cos'è?"]
HELD_OUT_FRAMES = ["Mi spieghi {art}?", "Che cosa sai {di}?", "Sai dirmi cos'è {art}?"]


def definition_rows(answers: dict[str, str]):
    """Yield (question, answer, split); answers maps a topic's first question to its answer."""
    for key, art, di, su, plain in SUBJECTS:
        answer = answers[key]
        fields = {"art": art, "di": di, "su": su, "plain": plain}
        for frame in TRAIN_FRAMES:
            question = frame.format(**fields)
            for variant in dict.fromkeys((question, question.lower(), question.rstrip("?.!"))):
                yield variant, answer, "train"
        for frame in HELD_OUT_FRAMES:
            yield frame.format(**fields), answer, "validation"
